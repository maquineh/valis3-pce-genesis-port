#!/usr/bin/env python3
"""Block-level code-likeliness scan; lists the best code candidate regions."""
import os
import sys

DIR = "build/extracted/data"
BLK = 2048

# opcodes that dominate real 65C02 code but are not over-represented in tile data
CODE_OPS = set()
for o in (0x8D, 0xAD, 0x2C, 0x4C, 0x6C, 0x20, 0x60, 0x9D, 0x99, 0xBD, 0xB9,
          0xDD, 0xD9, 0xFD, 0xF9, 0x1D, 0x19, 0x3D, 0x39, 0x5D, 0x59, 0x7D,
          0x79, 0xA9, 0xA2, 0xA0, 0x85, 0x84, 0x86, 0x95, 0x94, 0x8A, 0x98,
          0x48, 0x68, 0x78, 0x18, 0xD8, 0x58, 0x38, 0xF8, 0xE8, 0xC8, 0xCA,
          0x88, 0xA5, 0x0A, 0x2A, 0x6A, 0xAA, 0xA8, 0xE0, 0xC0, 0xC9, 0xE9,
          0x29, 0x09, 0x49, 0x69, 0x0D, 0x2D, 0x4D, 0x6D, 0xCD, 0xED, 0x05,
          0x15, 0x25, 0x35, 0x45, 0x55, 0x65, 0x75, 0xA9, 0x10, 0xD0, 0xF0,
          0x90, 0xB0, 0x30, 0x50, 0x70, 0x24, 0x8C, 0xA4, 0xB4, 0xBC, 0xA6,
          0xB6, 0xBE, 0xC4, 0xE4, 0xEC, 0x8E, 0x9C, 0x9E, 0xC6, 0xE6, 0xCE,
          0xEE, 0x26, 0x66, 0x46, 0x06, 0x16, 0x36, 0x56, 0x76, 0x2E, 0x6E,
          0x4E, 0x0E, 0x1E, 0x3E, 0x5E, 0x7E, 0xDE, 0xFE, 0x11, 0x31, 0x51,
          0x71, 0x91, 0xB1, 0xD1, 0xF1, 0x01, 0x21, 0x41, 0x61, 0x81, 0xA1,
          0xC1, 0xE1, 0x4A, 0xEA, 0xA9, 0x40, 0x6B, 0x83):
    CODE_OPS.add(o)


def score(b):
    n = len(b)
    if n == 0:
        return 0.0, 0.0
    hit = sum(1 for x in b if x in CODE_OPS)
    z = sum(1 for x in b if x == 0)
    return hit / n, z / n


def scan(path):
    b = open(path, "rb").read()
    rows = []
    for off in range(0, len(b), BLK):
        s, z = score(b[off:off + BLK])
        rows.append((s, z, off))
    rows.sort(reverse=True)
    return b, rows


if __name__ == "__main__":
    files = sys.argv[1:] or sorted(os.path.join(DIR, f) for f in os.listdir(DIR))
    for p in files:
        name = os.path.basename(p)
        b, rows = scan(p)
        # merge contiguous high-score blocks into regions
        best = [r for r in rows if r[0] > 0.26][:8]
        print("== %s" % name)
        for s, z, off in best:
            print("   $%06X  code %.3f zero %.3f" % (off, s, z))
