#!/usr/bin/env python3
"""Pack the original-game sound effects used by the city and phase 2.

The four attack/hit windows come from the PSG residual of the original PC
Engine city recording (the known CD-DA music track was subtracted at its
measured 0.49 gain and 52.8577 s offset).  The jump window comes from the
original Japanese Genesis cartridge through Genesis Plus GX, PSG-only, as the
difference against a neutral run from the same save state.

Each sample is mono, 11,025 Hz, 8-bit sign-magnitude, aligned to the PCM
chip's 256-byte start-address granularity.  The table points at the silent
0x80 byte after the 0xff loop marker.  The Sub CPU uploads the packed effects
once; the player voice follows at the next 4 KiB bank.
"""
from pathlib import Path
import wave

import numpy as np
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parents[1]
SFX = ROOT / 'build/sfx'
OUT_DATA = ROOT / 'game/res/audio/city_sfx.bin'
OUT_HEADER = ROOT / 'game/src/city_sfx_lengths.h'
RATE = 11025
BANK = 4096
ALIGN = 256

# name, source, start seconds, end seconds
SOURCES = (
    ('sword', 'pce_attack1.wav', 0.10, 0.40),
    ('jump', 'press_b_diff.wav', 0.58, 0.88),
    ('hit', 'pce_attack2.wav', 0.10, 0.34),
    ('magic', 'pce_attack3.wav', 0.15, 0.38),
)


def load_mono(path):
    with wave.open(str(path), 'rb') as wav:
        assert wav.getsampwidth() == 2 and wav.getframerate() == 44100
        data = np.frombuffer(wav.readframes(wav.getnframes()), dtype='<i2')
        data = data.reshape(-1, wav.getnchannels()).astype(np.float32)
    return data.mean(axis=1)


def trim(samples, start, end):
    start = round(start * 44100)
    end = round(end * 44100)
    chunk = samples[start:end].copy()
    if not len(chunk):
        raise ValueError('empty window')
    # 2 ms fade in/out to avoid a click at the sample boundary.
    fade = max(1, RATE // 500)
    chunk[:fade] *= np.linspace(0, 1, fade, dtype=np.float32)
    chunk[-fade:] *= np.linspace(1, 0, fade, dtype=np.float32)
    chunk = resample_poly(chunk, RATE, 44100)
    peak = np.abs(chunk).max()
    if peak < 1:
        raise ValueError('silent window')
    # The RF5C164 stores sign-magnitude samples: 0x80 is +0, 0x01..0x7f are
    # negative magnitudes, 0x80..0xfe are positive, and 0xff is the loop
    # marker.  Clamp +127 away so no sample byte can be mistaken for 0xff.
    values = np.rint(chunk / peak * 126).astype(np.int16)
    encoded = np.where(values >= 0, 0x80 + values, -values).astype(np.uint8)
    assert 0xff not in encoded
    # Play the clip once, then loop on the silent 0x80 byte that follows the
    # 0xff marker.  The length table points at that silent byte.
    encoded = np.concatenate((encoded, np.array([0x80, 0xff], dtype=np.uint8)))
    return encoded


def main():
    bundle = bytearray()
    offsets = []
    lengths = []
    for name, filename, start, end in SOURCES:
        while len(bundle) % ALIGN:
            bundle.append(0x80)
        source = trim(load_mono(SFX / filename), start, end)
        offsets.append(len(bundle))
        lengths.append(len(source) - 2)
        bundle += source.tobytes()
        print('%-6s offset %5d  %5d bytes (%0.3f s at %d Hz)' %
              (name, offsets[-1], len(source), (len(source) - 2) / RATE, RATE))
    while len(bundle) % BANK:
        bundle.append(0x80)
    banks = len(bundle) // BANK
    OUT_DATA.write_bytes(bundle)
    OUT_HEADER.write_text(
        '/* Generated by tools/pack_city_sfx.py; 256-byte aligned samples. */\n'
        '#ifndef VALIS3_CITY_SFX_LENGTHS_H\n#define VALIS3_CITY_SFX_LENGTHS_H\n'
        'enum { CITY_SFX_COUNT = %d, CITY_SFX_BANKS = %d, CITY_SFX_BANK_BYTES = %d };\n'
        'static const unsigned short city_sfx_offsets[CITY_SFX_COUNT] = {%s};\n'
        'static const unsigned short city_sfx_lengths[CITY_SFX_COUNT] = {%s};\n'
        '#endif\n' % (len(lengths), banks, BANK,
                      ', '.join(str(n) for n in offsets),
                      ', '.join(str(n) for n in lengths)),
        encoding='ascii')
    print('wrote %s (%d bytes, %d banks) and %s' %
          (OUT_DATA, len(bundle), banks, OUT_HEADER))


if __name__ == '__main__':
    main()
